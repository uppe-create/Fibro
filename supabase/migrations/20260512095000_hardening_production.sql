-- Production hardening for Supabase.
-- Apply this only after moving administrative writes to Supabase Auth,
-- an Edge Function, or another trusted backend. The static MVP/local login uses
-- the anon key for dashboard/cadastro writes, so applying this before Auth users
-- and app_profiles exist will block cadastro, edicao, upload and export flows.

create table if not exists public.app_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('admin', 'attendant', 'viewer')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.app_profiles enable row level security;

drop policy if exists own_profile_read on public.app_profiles;
drop policy if exists admin_profile_read on public.app_profiles;

create policy own_profile_read
on public.app_profiles for select to authenticated
using (id = auth.uid());

create policy admin_profile_read
on public.app_profiles for select to authenticated
using (
  exists (
    select 1
    from public.app_profiles profile
    where profile.id = auth.uid()
      and profile.role = 'admin'
  )
);

create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  with resolved as (
    select coalesce(
      auth.jwt() ->> 'app_role',
      (
        select role
        from public.app_profiles
        where id = auth.uid()
        limit 1
      ),
      'viewer'
    ) as role
  )
  select case
    when role = 'admin' and coalesce(auth.jwt() ->> 'aal', '') <> 'aal2' then 'viewer'
    else role
  end
  from resolved;
$$;


create or replace function public.audit_registration_changes()
returns trigger
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_registration_id uuid;
  v_action text := 'Cadastro ' || lower(tg_op);
  v_event_code text := 'registration.changed';
  v_summary text := 'Cadastro alterado automaticamente';
  v_user_name text;
  v_reason text := 'Auditoria automatica por trigger';
begin
  if tg_op = 'DELETE' then
    v_registration_id := old.id;
  else
    v_registration_id := new.id;
  end if;

  if tg_op = 'UPDATE' then
    if old.deleted_at is null and new.deleted_at is not null then
      v_event_code := 'registration.archived';
      v_summary := 'Registro arquivado por trigger';
      v_reason := 'Arquivamento logico';
    elsif old.status is distinct from new.status then
      v_event_code := case
        when new.status = 'approved' then 'registration.approved'
        when new.status = 'issued' then 'card.issued'
        when new.status = 'cancelled' then 'registration.cancelled'
        else 'registration.changed'
      end;
      v_summary := case
        when new.status = 'approved' then 'Cadastro aprovado por trigger'
        when new.status = 'issued' then 'Carteirinha emitida por trigger'
        when new.status = 'cancelled' then 'Carteirinha cancelada por trigger'
        else 'Cadastro alterado por trigger'
      end;
      v_reason := 'Status: ' || coalesce(old.status, '-') || ' -> ' || coalesce(new.status, '-');
    else
      v_event_code := 'registration.edited';
      v_summary := 'Cadastro editado por trigger';
    end if;
  elsif tg_op = 'INSERT' then
    v_event_code := 'registration.created';
    v_summary := 'Cadastro inserido por trigger';
  elsif tg_op = 'DELETE' then
    v_event_code := 'registration.archived';
    v_summary := 'Cadastro removido por trigger';
  end if;

  select full_name
  into v_user_name
  from public.app_profiles
  where id = auth.uid()
  limit 1;

  insert into public.audit_logs("registrationId", "userId", "userName", ip, timestamp, action, reason, event_code, category, severity, target_type, target_id, summary, details, metadata_json)
  values (
    v_registration_id,
    auth.uid()::text,
    coalesce(nullif(v_user_name, ''), nullif(auth.jwt() ->> 'email', ''), 'Banco de dados'),
    public.request_ip(),
    now(),
    v_action,
    v_reason,
    v_event_code,
    'registration',
    case when v_event_code in ('registration.archived', 'registration.cancelled') then 'warning' else 'info' end,
    'registration',
    v_registration_id,
    v_summary,
    v_reason,
    jsonb_build_object('source', 'trigger', 'operation', tg_op)
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists trigger_audit_registrations on public.registrations;
create trigger trigger_audit_registrations
after insert or update or delete on public.registrations
for each row execute function public.audit_registration_changes();

revoke all on function public.audit_registration_changes() from public;

create or replace function public.validate_cipf(p_id uuid, p_sig text)
returns table (
  id uuid,
  "fullName" text,
  "cpfMasked" text,
  "issueDate" text,
  "expiryDate" text,
  status text,
  "visualSignature" text,
  checksum text
)
language plpgsql
volatile
security definer
set search_path = public
as $$
begin
  if not public.check_rate_limit('validate_cipf', 5, 60) then
    raise exception 'RATE_LIMITED: muitas consultas. Tente novamente em 1 minuto.';
  end if;

  return query
  select
    pv.id,
    pv."fullName",
    pv."cpfMasked",
    pv."issueDate",
    pv."expiryDate",
    pv.status,
    pv."visualSignature",
    pv.checksum
  from public.public_validations pv
  where pv.id = p_id
    and upper(trim(pv."visualSignature")) = upper(trim(p_sig))
    and pv.deleted_at is null
    and pv.status = 'issued'
  limit 1;
end;
$$;

create or replace function public.validate_cipf_public(p_registry text, p_sig text)
returns table (
  id uuid,
  "fullName" text,
  "cpfMasked" text,
  "issueDate" text,
  "expiryDate" text,
  status text,
  "visualSignature" text,
  checksum text
)
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_registry text := trim(coalesce(p_registry, ''));
  v_registry_clean text := upper(regexp_replace(trim(coalesce(p_registry, '')), '[^a-zA-Z0-9]', '', 'g'));
  v_sig text := upper(regexp_replace(trim(coalesce(p_sig, '')), '[^a-zA-Z0-9]', '', 'g'));
begin
  if not public.check_rate_limit('validate_cipf_public', 5, 60) then
    raise exception 'RATE_LIMITED: muitas consultas. Tente novamente em 1 minuto.';
  end if;

  if length(v_registry_clean) < 6 or length(v_sig) < 6 then
    return;
  end if;

  if v_registry ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    return query
    select
      pv.id,
      pv."fullName",
      pv."cpfMasked",
      pv."issueDate",
      pv."expiryDate",
      pv.status,
      pv."visualSignature",
      pv.checksum
    from public.public_validations pv
    where pv.id = v_registry::uuid
      and upper(regexp_replace(coalesce(pv."visualSignature", ''), '[^a-zA-Z0-9]', '', 'g')) = v_sig
      and pv.deleted_at is null
      and pv.status = 'issued'
    limit 1;
    return;
  end if;

  return query
  select
    pv.id,
    pv."fullName",
    pv."cpfMasked",
    pv."issueDate",
    pv."expiryDate",
    pv.status,
    pv."visualSignature",
    pv.checksum
  from public.public_validations pv
  where replace(upper(pv.id::text), '-', '') like v_registry_clean || '%'
    and upper(regexp_replace(coalesce(pv."visualSignature", ''), '[^a-zA-Z0-9]', '', 'g')) = v_sig
    and pv.deleted_at is null
    and pv.status = 'issued'
  order by pv."issueDate" desc
  limit 1;
end;
$$;

revoke all on function public.validate_cipf(uuid, text) from public;
grant execute on function public.validate_cipf(uuid, text) to anon, authenticated;
revoke all on function public.validate_cipf_public(text, text) from public;
grant execute on function public.validate_cipf_public(text, text) to anon, authenticated;

create or replace function public.admin_transition_registration(
  p_registration_id uuid,
  p_action text,
  p_reason text default null
)
returns public.registrations
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_action text := lower(trim(coalesce(p_action, '')));
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
  v_registration public.registrations%rowtype;
  v_issue_date text := to_char(current_date, 'DD/MM/YYYY');
  v_expiry_date text := to_char((current_date + interval '2 years')::date, 'DD/MM/YYYY');
begin
  if auth.uid() is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  if public.current_app_role() <> 'admin' then
    raise exception 'FORBIDDEN';
  end if;

  select *
  into v_registration
  from public.registrations
  where id = p_registration_id
    and deleted_at is null
  limit 1;

  if not found then
    raise exception 'NOT_FOUND';
  end if;

  if v_action in ('cancel', 'renew', 'reissue', 'archive') and v_reason is null then
    raise exception 'REASON_REQUIRED';
  end if;

  case v_action
    when 'approve' then
      update public.registrations set status = 'approved' where id = p_registration_id;
      update public.public_validations set status = 'approved' where id = p_registration_id;
      update public.registration_index
      set status = 'approved', updated_at = now()
      where cpf = regexp_replace(coalesce(v_registration.cpf, ''), '\D', '', 'g');

      perform public.log_audit_event(
        p_action => 'Cadastro aprovado',
        p_registration_id => p_registration_id,
        p_reason => coalesce(v_reason, 'Cadastro aprovado para emissao administrativa'),
        p_event_code => 'registration.approved',
        p_category => 'workflow',
        p_severity => 'info',
        p_target_type => 'registration',
        p_target_label => v_registration."fullName",
        p_summary => 'Cadastro aprovado',
        p_details => coalesce(v_reason, 'Cadastro aprovado para emissao administrativa')
      );

    when 'issue' then
      if coalesce(v_registration.status, 'under_review') = 'approved' then
        update public.registrations
        set status = 'issued',
            "issueDate" = v_issue_date,
            "expiryDate" = v_expiry_date
        where id = p_registration_id;

        update public.public_validations
        set status = 'issued',
            "issueDate" = v_issue_date,
            "expiryDate" = v_expiry_date
        where id = p_registration_id;

        update public.registration_index
        set status = 'issued', updated_at = now()
        where cpf = regexp_replace(coalesce(v_registration.cpf, ''), '\D', '', 'g');

        perform public.log_audit_event(
          p_action => 'Carteirinha emitida',
          p_registration_id => p_registration_id,
          p_reason => coalesce(v_reason, 'Emissao administrativa para impressao'),
          p_event_code => 'card.issued',
          p_category => 'workflow',
          p_severity => 'sensitive',
          p_target_type => 'registration',
          p_target_label => v_registration."fullName",
          p_summary => 'Carteirinha emitida',
          p_details => coalesce(v_reason, 'Emissao administrativa para impressao')
        );
      else
        perform public.log_audit_event(
          p_action => 'Acesso a impressao',
          p_registration_id => p_registration_id,
          p_reason => 'Carteirinha ja emitida',
          p_event_code => 'card.print_accessed',
          p_category => 'workflow',
          p_severity => 'info',
          p_target_type => 'registration',
          p_target_label => v_registration."fullName",
          p_summary => 'Tela de impressao acessada',
          p_details => 'Carteirinha ja emitida'
        );
      end if;

    when 'cancel' then
      update public.registrations set status = 'cancelled' where id = p_registration_id;
      update public.public_validations set status = 'cancelled' where id = p_registration_id;
      update public.registration_index
      set status = 'cancelled', updated_at = now()
      where cpf = regexp_replace(coalesce(v_registration.cpf, ''), '\D', '', 'g');

      perform public.log_audit_event(
        p_action => 'Carteirinha cancelada',
        p_registration_id => p_registration_id,
        p_reason => v_reason,
        p_event_code => 'registration.cancelled',
        p_category => 'workflow',
        p_severity => 'sensitive',
        p_target_type => 'registration',
        p_target_label => v_registration."fullName",
        p_summary => 'Carteirinha cancelada',
        p_details => v_reason
      );

    when 'renew' then
      update public.registrations
      set status = 'approved',
          "issueDate" = v_issue_date,
          "expiryDate" = v_expiry_date
      where id = p_registration_id;

      update public.public_validations
      set status = 'approved',
          "issueDate" = v_issue_date,
          "expiryDate" = v_expiry_date
      where id = p_registration_id;

      update public.registration_index
      set status = 'approved', updated_at = now()
      where cpf = regexp_replace(coalesce(v_registration.cpf, ''), '\D', '', 'g');

      perform public.log_audit_event(
        p_action => 'Cadastro renovado',
        p_registration_id => p_registration_id,
        p_reason => v_reason,
        p_event_code => 'registration.renewed',
        p_category => 'workflow',
        p_severity => 'sensitive',
        p_target_type => 'registration',
        p_target_label => v_registration."fullName",
        p_summary => 'Cadastro renovado',
        p_details => v_reason || '; nova validade=' || v_expiry_date
      );

    when 'reissue' then
      perform public.log_audit_event(
        p_action => 'Segunda via registrada',
        p_registration_id => p_registration_id,
        p_reason => v_reason,
        p_event_code => 'card.reissued',
        p_category => 'workflow',
        p_severity => 'sensitive',
        p_target_type => 'registration',
        p_target_label => v_registration."fullName",
        p_summary => 'Segunda via registrada',
        p_details => v_reason
      );

    when 'archive' then
      update public.registrations set status = 'cancelled' where id = p_registration_id;
      update public.public_validations set status = 'cancelled' where id = p_registration_id;
      update public.registration_index
      set status = 'cancelled', updated_at = now()
      where cpf = regexp_replace(coalesce(v_registration.cpf, ''), '\D', '', 'g');

      perform public.log_audit_event(
        p_action => 'Cadastro arquivado',
        p_registration_id => p_registration_id,
        p_reason => v_reason,
        p_event_code => 'registration.archived',
        p_category => 'workflow',
        p_severity => 'sensitive',
        p_target_type => 'registration',
        p_target_label => v_registration."fullName",
        p_summary => 'Cadastro arquivado',
        p_details => v_reason
      );

    else
      raise exception 'UNSUPPORTED_ACTION';
  end case;

  select *
  into v_registration
  from public.registrations
  where id = p_registration_id
  limit 1;

  return v_registration;
end;
$$;

create or replace function public.admin_request_export(
  p_export_kind text,
  p_filters_json jsonb default '{}'::jsonb
)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_kind text := lower(trim(coalesce(p_export_kind, 'dashboard_csv')));
  v_summary text;
  v_event_code text;
begin
  if auth.uid() is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  if public.current_app_role() <> 'admin' then
    raise exception 'FORBIDDEN';
  end if;

  v_event_code := case v_kind
    when 'dashboard_pdf' then 'export.dashboard_pdf'
    when 'monthly_pdf' then 'export.monthly_pdf'
    when 'backup_json' then 'system.backup_downloaded'
    else 'export.dashboard_csv'
  end;

  v_summary := case v_kind
    when 'dashboard_pdf' then 'Exportacao PDF solicitada'
    when 'monthly_pdf' then 'Relatorio mensal solicitado'
    when 'backup_json' then 'Backup JSON solicitado'
    else 'Exportacao CSV solicitada'
  end;

  perform public.log_audit_event(
    p_action => v_summary,
    p_event_code => v_event_code,
    p_category => case when v_kind = 'backup_json' then 'system' else 'export' end,
    p_severity => 'sensitive',
    p_target_type => 'system',
    p_target_label => 'Exportacao administrativa',
    p_summary => v_summary,
    p_details => left(coalesce(p_filters_json::text, '{}'), 4000),
    p_metadata_json => jsonb_build_object('exportKind', v_kind, 'filters', coalesce(p_filters_json, '{}'::jsonb))
  );
